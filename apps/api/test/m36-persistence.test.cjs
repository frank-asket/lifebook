// Opt in only against a disposable loopback database. Fixtures always roll back.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { PrismaClient } = require('@prisma/client');
const { randomBytes } = require('node:crypto');
const { BibleReadingService } = require('../dist/bible-reading/bible-reading.service');
const { BibleAnnotationsService } = require('../dist/bible-annotations/bible-annotations.service');
const { MeditationService } = require('../dist/meditation/meditation.service');
const { DailyWordService } = require('../dist/daily-word/daily-word.service');
const url = process.env.LIFEBOOK_M36_TEST_DATABASE_URL;
test('M3.6 database persistence, ownership, completion semantics, and encrypted notes', { skip: !url }, async () => {
  const target = new URL(url);
  assert.equal(target.hostname, '127.0.0.1');
  assert.equal(target.pathname, '/lifebook_restore');
  const db = new PrismaClient({ datasources: { db: { url } } });
  const rollback = new Error('ROLLBACK_M36_TEST');
  const previousKey = process.env.BIBLE_NOTES_ENCRYPTION_KEY;
  process.env.BIBLE_NOTES_ENCRYPTION_KEY = randomBytes(32).toString('hex');
  try {
    await assert.rejects(db.$transaction(async tx => {
      const prefix = `m36-test-${Date.now()}`;
      const first = await tx.user.create({ data: { oidcSubject: `${prefix}-first` } });
      const second = await tx.user.create({ data: { oidcSubject: `${prefix}-second` } });
      const identity = async auth => auth === 'first' ? first.id : second.id;
      const meditation = new MeditationService();
      const reading = new BibleReadingService();
      const annotations = new BibleAnnotationsService(meditation);
      const daily = new DailyWordService(meditation);
      for (const service of [meditation, reading, annotations, daily]) await service.onModuleDestroy();
      meditation.db = tx; meditation.userId = identity;
      reading.db = tx; reading.userId = identity;
      annotations.db = tx;
      // Keep Daily Word's transaction inside the enclosing rollback fixture.
      daily.db = new Proxy(tx, { get: (target, key) => key === '$transaction' ? fn => fn(tx) : target[key] });
      await reading.saveHistory('first', { locale: 'fr', chapterId: 'LUK.1' });
      await reading.saveHistory('first', { locale: 'en', chapterId: 'GEN.1' });
      await reading.saveHistory('first', { locale: 'fr', chapterId: 'LUK.1' });
      assert.equal((await reading.history('first')).length, 2);
      assert.equal((await reading.continueReading('first')).chapterId, 'LUK.1');
      assert.deepEqual(await reading.history('second'), []);
      const enrollment = await reading.enroll('first', 'discover-jesus');
      assert.equal((await reading.enroll('first', 'discover-jesus')).id, enrollment.id);
      assert.equal((await reading.myPlans('first', 'fr'))[0].completedDays, 0, 'opening a chapter must not complete a plan day');
      await reading.completeDay('first', enrollment.id, 1);
      await reading.completeDay('first', enrollment.id, 1);
      const progress = (await reading.myPlans('first', 'fr'))[0];
      assert.equal(progress.completedDays, 1);
      assert.equal(progress.plan.title, 'Découvrir Jésus');
      await assert.rejects(reading.completeDay('second', enrollment.id, 1), /not found/);
      await assert.rejects(reading.completeDay('first', enrollment.id, 22), /Invalid plan day/);
      const note = await annotations.save('first', { passageId: 'LUK.1.1', locale: 'fr', bookmark: true, highlight: 'yellow', note: 'Synthetic private note' });
      const stored = await tx.bibleAnnotation.findUnique({ where: { id: note.id } });
      assert.ok(stored.noteCiphertext.startsWith('v1:'));
      assert.ok(!stored.noteCiphertext.includes('Synthetic private note'));
      assert.equal((await annotations.list('first'))[0].note, 'Synthetic private note');
      assert.deepEqual(await annotations.list('second'), []);
      await assert.rejects(annotations.remove('second', note.id), /not found/);
      const session = await daily.today('first', 'Africa/Accra');
      assert.equal((await daily.today('first', 'Africa/Accra')).id, session.id);
      await daily.saveReflection('first', session.id, 'Synthetic daily reflection');
      await assert.rejects(daily.saveReflection('second', session.id, 'Wrong owner'), /not found/);
      for (const step of ['UNDERSTAND', 'MEDITATE', 'REFLECT', 'PRAY', 'LIVE']) await daily.completeStep('first', session.id, step);
      await daily.completeStep('first', session.id, 'LIVE');
      assert.equal((await daily.stats('first')).completedSessions, 1);
      assert.equal((await daily.history('first'))[0].reflection.content, 'Synthetic daily reflection');
      assert.deepEqual(await daily.history('second'), []);
      const item = await tx.meditation.create({ data: { slug: prefix, title: 'Fixture meditation', scriptureReference: 'LUK.1', explanation: 'Fixture', questions: [], guidedPrayer: 'Fixture', isPublished: true } });
      await meditation.reflect(item.id, 'Synthetic meditation reflection', 'first');
      assert.equal((await meditation.myState(item.id, 'first')).reflection, 'Synthetic meditation reflection');
      assert.equal((await meditation.myState(item.id, 'second')).reflection, '');
      await meditation.complete(item.id, 'first');
      assert.equal((await meditation.history('first')).length, 1);
      assert.deepEqual(await meditation.history('second'), []);
      throw rollback;
    }, { timeout: 20000 }), error => error === rollback);
  } finally {
    if (previousKey === undefined) delete process.env.BIBLE_NOTES_ENCRYPTION_KEY;
    else process.env.BIBLE_NOTES_ENCRYPTION_KEY = previousKey;
    await db.$disconnect();
  }
});
